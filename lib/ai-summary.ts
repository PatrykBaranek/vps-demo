import * as Sentry from '@sentry/nextjs';
import { streamText } from 'ai';
import { createOpenRouter } from '@openrouter/ai-sdk-provider';
import { encode } from 'gpt-tokenizer';

import type { FeedItem } from './rss';
import { readSummary, writeSummary } from './summary-store';

const openrouter = createOpenRouter({
  apiKey: process.env.OPENROUTER_API_KEY,
  headers: {
    'X-OpenRouter-Title': 'YourApp',
    'HTTP-Referer': 'https://yourapp.com',
  },
});

// `openrouter/free` routes to whichever free model is available. Set
// OPENROUTER_MODEL to pin a specific (e.g. `:free`) model instead.
const MODEL_ID = process.env.OPENROUTER_MODEL || 'openrouter/free';

const languageInstructions = {
  en: 'Write the summary in English.',
  pl: 'Write the summary in Polish (Polski).',
  de: 'Write the summary in German (Deutsch).',
};

export type SummaryLanguage = keyof typeof languageInstructions;

export const summaryLanguages = Object.keys(languageInstructions) as SummaryLanguage[];

export function isSummaryLanguage(value: unknown): value is SummaryLanguage {
  return typeof value === 'string' && value in languageInstructions;
}

// Briefings are regenerated by the scheduled refresh; anything older than
// this is regenerated on demand. Article summaries never go stale.
export const BRIEFING_MAX_AGE_MS = 3 * 60 * 60 * 1000;

export const briefingKey = (language: SummaryLanguage, category: string) =>
  `briefing:${language}:${category}`;

export const articleKey = (language: SummaryLanguage, link: string) =>
  `article:${language}:${link}`;

const MAX_INPUT_TOKENS = 2048;
const SYSTEM_OVERHEAD = 256;

function buildPrompt(items: Pick<FeedItem, 'title' | 'contentSnippet'>[]): string {
  // Token-aware truncation: items are already sorted newest-first from the RSS fetch,
  // so iterating in-order naturally keeps the most recent articles.
  const itemTexts: string[] = [];
  let totalTokens = 0;
  const budget = MAX_INPUT_TOKENS - SYSTEM_OVERHEAD;

  for (const it of items) {
    const text = `Title: ${it.title}\n${it.contentSnippet ? `${it.contentSnippet}\n` : ''}`;
    const tokens = encode(text).length;
    if (totalTokens + tokens > budget && itemTexts.length > 0) break;
    itemTexts.push(text);
    totalTokens += tokens;
  }

  return itemTexts.join('\n\n');
}

interface Generation {
  // Text chunks for the requester that started the generation.
  stream: ReadableStream<string>;
  // Resolves with the full summary once it is generated and stored.
  done: Promise<string>;
}

const inFlight = new Map<string, Promise<string>>();

function startGeneration(
  key: string,
  items: Pick<FeedItem, 'title' | 'contentSnippet'>[],
  language: SummaryLanguage,
): Generation {
  const result = streamText({
    model: openrouter.chat(MODEL_ID),
    system: [
      'You are a professional news editor.',
      'Summarize the provided RSS feed articles into a concise briefing grouped by theme.',
      'Use markdown with bold section headers and bullet points.',
      'Write in a neutral, editorial tone.',
      'Do not address the reader. Do not include greetings, sign-offs, offers to help, or meta-commentary about the summary.',
      languageInstructions[language],
      'Output only the summary itself — nothing before or after it.',
    ].join(' '),
    prompt: buildPrompt(items),
  });

  const textStream = result.stream.pipeThrough(
    new TransformStream<{ type: string; text?: string; error?: unknown }, string>({
      transform(part, controller) {
        if (part.type === 'text-delta' && part.text) controller.enqueue(part.text);
        if (part.type === 'error') controller.error(part.error);
      },
    }),
  );

  // One branch goes to the requester, the other is drained here so the
  // summary is still finished and stored if that requester disconnects.
  const [clientStream, storeStream] = textStream.tee();

  const done = (async () => {
    let summary = '';
    const reader = storeStream.getReader();
    while (true) {
      const { done: finished, value } = await reader.read();
      if (finished) break;
      summary += value;
    }
    summary = summary.trim();
    if (!summary) throw new Error('The model returned an empty summary');
    await writeSummary(key, summary);
    return summary;
  })();

  inFlight.set(key, done);
  done
    .catch((error) => {
      console.error(`AI summary generation failed for ${key}:`, error);
      Sentry.captureException(error, { tags: { feature: 'ai-summary' }, extra: { key } });
    })
    .finally(() => inFlight.delete(key));

  return { stream: clientStream, done };
}

const streamHeaders = {
  'Content-Type': 'text/plain; charset=utf-8',
  // Stop reverse proxies (nginx, Cloudflare) from buffering or compressing
  // the stream, which would hold it back until generation finishes.
  'Cache-Control': 'no-cache, no-transform',
  'X-Accel-Buffering': 'no',
};

// Returns the shared summary for `key`: straight from the store when fresh,
// by waiting on a generation another request already started, or by
// starting one and streaming it.
export async function summaryResponse(
  key: string,
  items: Pick<FeedItem, 'title' | 'contentSnippet'>[],
  language: SummaryLanguage,
  maxAgeMs = Infinity,
): Promise<Response> {
  const stored = await readSummary(key);
  if (stored && Date.now() - stored.createdAt < maxAgeMs) {
    return new Response(stored.summary, { headers: streamHeaders });
  }

  const pending = inFlight.get(key);
  if (pending) {
    try {
      return new Response(await pending, { headers: streamHeaders });
    } catch {
      return new Response('Summary generation failed', { status: 502 });
    }
  }

  const { stream } = startGeneration(key, items, language);

  // Wait for the first chunk so a failure before any text (e.g. a free
  // model's rate limit) becomes a 502 instead of a dropped connection.
  const reader = stream.getReader();
  let first: ReadableStreamReadResult<string>;
  try {
    first = await reader.read();
  } catch {
    return new Response('Summary generation failed', { status: 502 });
  }

  const body = new ReadableStream<string>({
    start(controller) {
      if (first.done) controller.close();
      else controller.enqueue(first.value);
    },
    async pull(controller) {
      const { done, value } = await reader.read();
      if (done) controller.close();
      else controller.enqueue(value);
    },
    cancel(reason) {
      return reader.cancel(reason);
    },
  });
  return new Response(body.pipeThrough(new TextEncoderStream()), { headers: streamHeaders });
}

// Regenerates and stores a summary regardless of its age (used by the
// scheduled refresh). Reuses a generation that is already running.
export async function refreshSummary(
  key: string,
  items: Pick<FeedItem, 'title' | 'contentSnippet'>[],
  language: SummaryLanguage,
): Promise<string> {
  const pending = inFlight.get(key);
  if (pending) return pending;

  const { stream, done } = startGeneration(key, items, language);
  await stream.cancel();
  return done;
}
